"""
Preprocess the QA dataset to parquet format
"""

import re
import os
import datasets

from verl.utils.hdfs_io import copy, makedirs
import argparse


SYS_PROMPT = """You are a helpful assistant that solves the user's question step by step using the Wikipedia search tool. In each step, you must first perform reasoning, and then decide whether to invoke the search tool or provide the final answer. You may repeat the search process multiple times if needed. You must enclose your reasoning process within <reasoning> </reasoning> tags, your search query within <search> </search> tags, and your final answer within <answer> </answer> tags. Search results will be returned within <information> </information> tags each time you invoke the search tool.
Example format:
<reasoning> I need to find the capital of Singapore. </reasoning>
<search> capital of Singapore </search>
<information> ... </information>
<reasoning> The search result confirms the capital. I can now answer. </reasoning>
<answer> Singapore </answer>"""


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--local_dir', default='./data/nq_search')
    parser.add_argument('--hdfs_dir', default=None)
    parser.add_argument('--template_type', type=str, default='base')
    parser.add_argument('--data_sources', default='nq')

    args = parser.parse_args()

    # data_source = 'nq'
    data_sources = args.data_sources.split(',')
    all_dataset = []

    for data_source in data_sources:

        dataset = datasets.load_dataset('RUC-NLPIR/FlashRAG_datasets', data_source)

        train_dataset = dataset['train']

        # add a row to each data item that represents a unique id
        def make_map_fn(split):

            def process_fn(example, idx):
                question = example['question'].strip()
                if question[-1] != '?':
                    question += '?'
                solution = {
                    "target": example['golden_answers'],
                }

                data = {
                    "data_source": data_source,
                    "prompt": [{
                        "role": "system",
                        "content": SYS_PROMPT,
                    },{
                        "role": "user",
                        "content": question,
                    }],
                    "ability": "fact-reasoning",
                    "reward_model": {
                        "style": "rule",
                        "ground_truth": solution
                    },
                    "extra_info": {
                        'split': split,
                        'index': idx,
                    }
                }
                return data

            return process_fn

        train_dataset = train_dataset.map(function=make_map_fn('train'), with_indices=True)
        all_dataset.append(train_dataset)

    local_dir = args.local_dir
    hdfs_dir = args.hdfs_dir

    all_train_dataset = datasets.concatenate_datasets(all_dataset)
    all_train_dataset.to_parquet(os.path.join(local_dir, 'train.parquet'))

    if hdfs_dir is not None:
        makedirs(hdfs_dir)

        copy(src=local_dir, dst=hdfs_dir)
